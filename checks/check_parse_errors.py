"""Качество входных JSON: отсутствующие, повреждённые и отклонённые ответы.

Технические строки добавляются движком автоматически даже для старых конфигураций.
Этот файл можно загрузить как собственную проверку, если нужны свои параметры или
названия. Тогда её строки будут дополнительными к обязательному отчёту качества.
Используется Mart API вместо чтения пути на файловой системе контейнера.
"""
def run(mart, params=None):
    if mart.input_total_apps() is None:
        raise ValueError('В старой витрине нет журнала входных ответов. Нужен новый полный расчёт.')
    limit=int((params or {}).get('app_ids_limit',20))
    return mart.input_quality_checks(max(0,min(limit,100)))
